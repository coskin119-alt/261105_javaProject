package day04;

public class For05 {

	public static void main(String[] args) {
		// 구구단

		System.out.println("구구단 책받침");
		System.out.println("-------------------------------------------------------------");
		for (int i = 1; i <= 9; i++) {
			for (int j = 2; j <= 9; j++) {
				System.out.print(j + " X " + i + " = " + i*j + "\t");
			}
			System.out.println();
		}
		System.out.println("-------------------------------------------------------------");
			
		
		
		
		
		
	}

}
