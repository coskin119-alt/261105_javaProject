package day09;

public class Class02 {

	/* 클래스 구성 순서
	 * 
	 * 1. 멤버변수 : 접근제어자 자료형 변수명; // 멤버변수 선언
	 * 
	 * 2. 생성자 : 객체를 생성하고 초기화할 때 호출되는 인스턴스 초기화 메서드 
	 * 
	 * 3. (멤버)메서드
	 * 
	 * 클래스 : 객체를 생성하기 위한 설계도
	 * 객체 : 클래서로 부터 생성된 제품 (object)
	 * 메서드 : 제품의 기능 (object가 할 수 있는 일)
	 * 메버변수 : 제품의 속성 (공통의 메서드에서 필요로 하는 값들을 저장 속성)
	 * 
	 * 클래스는 다른 클래스와 겹치치 않게 정의
	 * 하나의 파일안에 여러개의 클래스를 정의할 수 있으나 거의 사용 안함.
	 * 
	 * 1. 한 파일에 하나의 클래서를 생성
	 * 2. 클래스에서 public을 붙일 수 있는 클래스는 파일명과 같을때만 가능함.
	 * 3. 접근제어자는 클래서, 메서드, 멤버변수 모두에서 사용
	 * 4. 메서드는 public 가 일반적
	 * 5. 멤버변수는 private 가 일반적
	 * 6. 멤버변수가 private 이면 다른 클래스에서 접근 금지
	 * 7. 멤버변수를 다른 클래서에 접근 가능하도록 하려면 메서드를 별도 생성 사용
	 *   - getter : 값을 가져올 때
	 *   - setter : 값을 저장할 때
	 *    
	 *    
	 * 객체 선언 > 생성 : new
	 * 클래스명 객체형 = new 생성자();
	 * 클래스명 객체명;  // null
	 * 
	 * 메서드 사용방법 (static 이 안붙은 일반(객체) 메서드)
	 *   - 같은 클래서 내부에서 호출할 경우 => 메서드명();
	 *   - static 있거나 다른 클래서에서 호출할 경우 => 객체 선언후 객체명.메서드명();
	 * 
	 * class 클래서명 { 
	 *   - 클래스명은 반드시 대문자로 시작
	 *   - 한 패키지 안에서 같은 이름의 클래스 불가
	 * }
	 * 
	 * 
	 */
	
	
	
	
	
	
}
