package day11;

public class Static01 {

	public static void main(String[] args) {
		// static : 전역변수 / 전역메서드 => 객체없이 사용가능 (new 없이)
		// 멤버변수 : 객체의 변수, 객체의 메서드
		// 구조상 클래식 내부에 있지만 클래스 외부에 존재하는 것으로  
		/*
		 * 전역변수는 모든 객체에 공통으로 이용가능
		 * 프로그램이 실행되면서 바로 메모리에 옮겨서 ~ 프로그램을 종료할때 소멸
		 * - 객체 생성없이 클래스가 만들어지면 생성
		 * - 객체 생성없이 클래스.변수명 / 클래스.메서드명() 호출 가능
		 * - 클래스의 멤버변수, 메서드에서 하나의 멤버변수가 모든 객체에 공유되어야 할 때 사용
		 * 
		 * static 이 안 붙은 멤버변수/메서드 => 객체의 멤버변수/개체의 메서드
		 * - 각 객체를 통해 생성되고, 초기화되고, 사용된다.
		 * - 객체를 생성하지 않으면 (new) 생성되지 않고, 사용될 수 없다.
		 * - 각 객체마다 독립적으로 존재
		 * 
		 * 클래스의 멤버와 객체의 멤버는 생성되는 시점이 다르다.
		 * 객체의 멤버 => new 가 실행되면 생성
		 * 클래서의 멤버 => 클래스가 생성되면 (내가 작성하는 시점)
		 * 사용하는 시점도 다르다.
		 * 
		 * 객체의 멤버는 클래스가 생성되고, 객체 생성 (new) 후 사용 가능
		 * 클래스 멤버는 클래스가 생성되면 바로 사용 가능
		 * - 클래스 멤버는 클래스 멤버변수 / 클래스 메서드 에서 둘다 사용 가능
		 * - 객체 멤버는 클래스 멤버에서 사용 불가 (객체 생성이 안되어 있을 수 있기 때문)
		 * - static 이 붙은 메서드에서 일반메서드 직접 호출 불가능
		 * 
		 */
		

	}

}
